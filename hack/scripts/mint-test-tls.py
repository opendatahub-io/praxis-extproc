#!/usr/bin/env python3
"""Regenerate KIND/demo TLS material for the base Deployment volume mount.

OpenShift service-ca does not run on KIND, but the base Deployment mounts
Secret `payload-processing-tls`. E2e/demo overlays ship a minted Secret
(`tls-secret.yaml`) built from `deploy/testdata/tls/`.
"""

from __future__ import annotations

import base64
import datetime
from pathlib import Path

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import rsa
from cryptography.x509.oid import NameOID

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "deploy" / "testdata" / "tls"
SECRET_PATHS = [
    ROOT / "deploy" / "overlays" / "e2e" / "workload" / "tls-secret.yaml",
    ROOT / "deploy" / "overlays" / "demo" / "workload" / "tls-secret.yaml",
]

SANS = [
    "payload-processing.istio-system.svc.cluster.local",
    "payload-processing.praxis-extproc.svc.cluster.local",
    "payload-processing.openshift-ingress.svc.cluster.local",
    "payload-pre-processing.istio-system.svc.cluster.local",
    "payload-pre-processing.openshift-ingress.svc.cluster.local",
]

SECRET_HEADER = """\
# Generated by hack/scripts/mint-test-tls.py — do not edit by hand.
# KIND has no OpenShift service-ca; base Deployment mounts this Secret.
"""


def main() -> None:
    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, SANS[0])])
    now = datetime.datetime.now(datetime.timezone.utc)
    cert = (
        x509.CertificateBuilder()
        .subject_name(name)
        .issuer_name(name)
        .public_key(key.public_key())
        .serial_number(x509.random_serial_number())
        .not_valid_before(now - datetime.timedelta(minutes=1))
        .not_valid_after(now + datetime.timedelta(days=3650))
        .add_extension(
            x509.SubjectAlternativeName([x509.DNSName(s) for s in SANS]),
            critical=False,
        )
        .sign(key, hashes.SHA256())
    )

    crt_pem = cert.public_bytes(serialization.Encoding.PEM)
    key_pem = key.private_bytes(
        serialization.Encoding.PEM,
        serialization.PrivateFormat.TraditionalOpenSSL,
        serialization.NoEncryption(),
    )

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "tls.crt").write_bytes(crt_pem)
    (OUT / "tls.key").write_bytes(key_pem)

    secret = (
        SECRET_HEADER
        + "apiVersion: v1\n"
        + "kind: Secret\n"
        + "metadata:\n"
        + "  name: payload-processing-tls\n"
        + "type: kubernetes\n"
        + "data:\n"
        + f"  tls.crt: {base64.b64encode(crt_pem).decode()}\n"
        + f"  tls.key: {base64.b64encode(key_pem).decode()}\n"
    )
    for path in SECRET_PATHS:
        path.write_text(secret)
        print(f"wrote {path}")
    print(f"wrote {OUT / 'tls.crt'} and {OUT / 'tls.key'}")


if __name__ == "__main__":
    main()
