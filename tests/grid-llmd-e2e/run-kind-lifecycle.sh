phase_log() { printf '%s %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$*" >>"$RUN_DIR/RUN-LOG.md"; }
phase_start() {
  ACTIVE_PHASE="$1"
  PHASE_START="$(date +%s)"
  phase_log "START $ACTIVE_PHASE"
}
phase_end() {
  local rc="$1" end duration logfile
  end="$(date +%s)"
  duration=$((end - PHASE_START))
  jq -cn --arg phase "$ACTIVE_PHASE" --arg status "$([[ "$rc" == 0 ]] && printf PASS || printf FAIL)" \
    --arg startedAt "$(date -u -d "@$PHASE_START" +%Y-%m-%dT%H:%M:%SZ)" \
    --arg finishedAt "$(date -u -d "@$end" +%Y-%m-%dT%H:%M:%SZ)" \
    --argjson exitCode "$rc" --argjson durationSeconds "$duration" \
    '{phase:$phase,status:$status,startedAt:$startedAt,finishedAt:$finishedAt,exitCode:$exitCode,durationSeconds:$durationSeconds}' \
    >>"$RUN_DIR/PHASES.jsonl"
  phase_log "END $ACTIVE_PHASE exit=$rc duration_seconds=$duration"
  [[ "$rc" == 0 ]] || return "$rc"
}
run_phase() {
  local name="$1"; shift
  local -a env_pairs=() cmd=()
  local previous_phase="$ACTIVE_PHASE" previous_start="$PHASE_START"
  while (($#)) && [[ "$1" != -- ]]; do env_pairs+=("$1"); shift; done
  [[ "${1:-}" == -- ]] && shift
  cmd=("$@")
  ((${#cmd[@]})) || { printf 'run_phase %s has no command\n' "$name" >&2; return 2; }
  # Repository helper scripts are not all marked executable. Invoke helpers
  # from this directory through Bash so behavior does not depend on checkout
  # file modes (which caused phases to fail with exit 126).
  if [[ "${cmd[0]}" == "$SCRIPT_DIR/"*.sh ]]; then
    cmd=(bash "${cmd[@]}")
  fi
  phase_start "$name"
  local logfile="$RUN_DIR/logs/$name.log" rc=0
  (
    for pair in "${env_pairs[@]}"; do
      [[ "$pair" == *=* ]] || exit 2
      export "${pair%%=*}=${pair#*=}"
    done
    exec "${cmd[@]}"
  ) >"$logfile" 2>&1 || rc=$?
  python3 "$SCRIPT_DIR/sanitize_diagnostics.py" <"$logfile" >"$logfile.sanitized"
  mv "$logfile.sanitized" "$logfile"
  phase_end "$rc" || true
  if ((rc != 0)); then
    # Keep the failed phase active so the top-level failure record does not
    # misattribute the failure to the caller's previous phase.
    ACTIVE_PHASE="$name"
    printf 'Phase %s failed (exit %s); sanitized log: %s\n' "$name" "$rc" "$logfile" >&2
    tail -n 60 "$logfile" >&2 || true
    return "$rc"
  fi
  ACTIVE_PHASE="$previous_phase"
  PHASE_START="$previous_start"
}

write_resource_sample() {
  local docker_cpus=0 docker_memory=0 disk_available disk_total cpu_usage
  if command -v docker >/dev/null && docker info >/dev/null 2>&1; then
    read -r docker_cpus docker_memory < <(docker info --format '{{.NCPU}} {{.MemTotal}}' 2>/dev/null || printf '0 0\n')
  fi
  disk_available="$(df -B1 --output=avail "$RUN_ROOT" | tail -n 1 | tr -d ' ')"
  disk_total="$(df -B1 --output=size "$RUN_ROOT" | tail -n 1 | tr -d ' ')"
  [[ -n "$DISK_INITIAL_AVAILABLE_BYTES" ]] || DISK_INITIAL_AVAILABLE_BYTES="$disk_available"
  cpu_usage="$(awk '$1=="usage_usec" {print $2}' /sys/fs/cgroup/cpu.stat 2>/dev/null || echo 0)"
  jq -cn --arg at "$(date -u +%Y-%m-%dT%H:%M:%S.%NZ)" \
    --argjson visibleCpus "$(nproc)" \
    --argjson memoryAvailableBytes "$(awk '/MemAvailable:/ {print $2*1024}' /proc/meminfo)" \
    --argjson memoryCurrentBytes "$(cat /sys/fs/cgroup/memory.current 2>/dev/null || echo 0)" \
    --argjson memoryPeakBytes "$(cat /sys/fs/cgroup/memory.peak 2>/dev/null || echo 0)" \
    --arg cpuMax "$(cat /sys/fs/cgroup/cpu.max 2>/dev/null || echo unavailable)" \
    --argjson cpuUsageUsec "$cpu_usage" \
    --argjson dockerCpus "$docker_cpus" --argjson dockerMemoryBytes "$docker_memory" \
    --argjson diskAvailableBytes "$disk_available" --argjson diskTotalBytes "$disk_total" \
    --argjson diskInitialAvailableBytes "$DISK_INITIAL_AVAILABLE_BYTES" \
    '{at:$at,visibleCpus:$visibleCpus,memoryAvailableBytes:$memoryAvailableBytes,cgroupMemoryCurrentBytes:$memoryCurrentBytes,cgroupMemoryPeakBytes:$memoryPeakBytes,cpuMax:$cpuMax,cgroupCpuUsageUsec:$cpuUsageUsec,dockerCpus:$dockerCpus,dockerMemoryBytes:$dockerMemoryBytes,diskAvailableBytes:$diskAvailableBytes,diskTotalBytes:$diskTotalBytes,diskConsumedSinceFirstSampleBytes:($diskInitialAvailableBytes-$diskAvailableBytes)}' \
    >>"$RUN_DIR/phase-metrics/resource-samples.jsonl"
}
resource_monitor() {
  while :; do write_resource_sample; sleep 10; done
}

capture_diagnostics() {
  [[ -s "$KUBECONFIG" && -n "$EXPECTED_API_SERVER" ]] || return 0
  local dir
  dir="$RUN_DIR/diagnostics/failure-$(date -u +%Y%m%dT%H%M%SZ)"
  mkdir -p "$dir"
  chmod 0700 "$dir"
  set +e
  kubectl --kubeconfig="$KUBECONFIG" --context="$KUBE_CONTEXT" get --raw=/readyz >"$dir/readyz.txt" 2>&1
  kubectl --kubeconfig="$KUBECONFIG" --context="$KUBE_CONTEXT" get nodes -o json \
    | jq '[.items[]|{name:.metadata.name,uid:.metadata.uid,conditions:.status.conditions,capacity:.status.capacity,allocatable:.status.allocatable}]' >"$dir/nodes.json" 2>&1
  kubectl --kubeconfig="$KUBECONFIG" --context="$KUBE_CONTEXT" get pods -A -o json \
    | jq '[.items[]|{namespace:.metadata.namespace,name:.metadata.name,uid:.metadata.uid,ownerReferences:.metadata.ownerReferences,nodeName:.spec.nodeName,phase:.status.phase,conditions:.status.conditions,containers:[.status.containerStatuses[]?|{name,ready,restartCount,state,lastState,image,imageID}]}]' >"$dir/pods.json" 2>&1
  kubectl --kubeconfig="$KUBECONFIG" --context="$KUBE_CONTEXT" get events -A --sort-by=.lastTimestamp -o json \
    | jq '[.items[-200:][]|{namespace:.metadata.namespace,reason:.reason,type:.type,message:.message,object:.involvedObject,lastTimestamp:.lastTimestamp,count:.count}]' >"$dir/events.json" 2>&1
  kubectl --kubeconfig="$KUBECONFIG" --context="$KUBE_CONTEXT" get deployments,statefulsets,services,endpointslices -A -o json \
    | jq '[.items[]|{kind,namespace:.metadata.namespace,name:.metadata.name,uid:.metadata.uid,generation:.metadata.generation,labels:.metadata.labels,selector:.spec.selector,replicas:.spec.replicas,observedGeneration:.status.observedGeneration,readyReplicas:.status.readyReplicas,availableReplicas:.status.availableReplicas,conditions:.status.conditions,images:[.spec.template.spec.containers[]?.image]}]' >"$dir/workloads.json" 2>&1
  kubectl --kubeconfig="$KUBECONFIG" --context="$KUBE_CONTEXT" get crds -o name >"$dir/crds.txt" 2>&1
  kubectl --kubeconfig="$KUBECONFIG" --context="$KUBE_CONTEXT" get helmreleases.helm.cattle.io -A -o name >"$dir/helm-releases.txt" 2>&1
  set -e
  find "$dir" -type f -print0 | while IFS= read -r -d '' file; do
    python3 "$SCRIPT_DIR/sanitize_diagnostics.py" <"$file" >"$file.sanitized" && mv "$file.sanitized" "$file"
  done
  chmod -R go-rwx "$dir"
}

stop_background() {
  if [[ -n "$PORT_FORWARD_PID" ]]; then kill "$PORT_FORWARD_PID" 2>/dev/null || true; wait "$PORT_FORWARD_PID" 2>/dev/null || true; PORT_FORWARD_PID=""; fi
  if [[ -n "$MONITOR_PID" ]]; then kill "$MONITOR_PID" 2>/dev/null || true; wait "$MONITOR_PID" 2>/dev/null || true; MONITOR_PID=""; fi
}
on_exit() {
  local rc=$?
  trap - EXIT ERR INT TERM
  stop_background
  if ((rc != 0)) && [[ -d "$RUN_DIR" ]]; then
    capture_diagnostics
    if [[ "$MODE" == cleanup ]]; then
      phase_log "CLEANUP-RETRY-FAILED phase=$ACTIVE_PHASE stage=$CLEANUP_STAGE exit=$rc; original lifecycle result preserved"
      printf 'Cleanup retry failed at stage %s (exit %s); original lifecycle result preserved\n' "$CLEANUP_STAGE" "$rc" >&2
      jq -n --arg status FAIL --arg phase "$ACTIVE_PHASE" --arg stage "$CLEANUP_STAGE" --arg run "$RUN_ID" --argjson exitCode "$rc" \
        '{status:$status,phase:$phase,stage:$stage,runId:$run,exitCode:$exitCode,originalLifecycleResultPreserved:true}' \
        >"$RUN_DIR/cleanup/RETRY-FAILURE.json"
    else
      phase_log "FAILED phase=$ACTIVE_PHASE exit=$rc; run-owned cluster retained for workflow cleanup step"
      jq -n --arg status FAIL --arg phase "$ACTIVE_PHASE" --arg run "$RUN_ID" --argjson exitCode "$rc" \
        '{status:$status,phase:$phase,runId:$run,exitCode:$exitCode,naturalCleanup:false,diagnosticsCaptured:true}' >"$RUN_DIR/RESULT.json"
    fi
  fi
  exit "$rc"
}
trap on_exit EXIT
trap 'exit $?' ERR
trap 'exit 130' INT TERM

helper(){ printf '%s/%s' "$SCRIPT_DIR" "$1"; }
source_value() { jq -er --arg name "$1" '.components[$name].resolved_sha' "$RUN_DIR/source-resolution/source-locks.json"; }
source_dir() { jq -er --arg name "$1" '.components[$name].worktree_path' "$RUN_DIR/source-resolution/source-locks.json"; }
source_context() { jq -er --arg name "$1" '.components[$name].build_context_sha256' "$RUN_DIR/source-resolution/source-locks.json"; }
image_ref() { cat "$RUN_DIR/images/$1/image-ref.txt"; }
image_repo() { local ref; ref="$(image_ref "$1")"; printf '%s\n' "${ref%@*}"; }
image_provenance() { printf '%s/images/%s/image-provenance-%s.json' "$RUN_DIR" "$1" "$1"; }
image_metadata() { printf '%s/images/%s/build-metadata-%s.json' "$RUN_DIR" "$1" "$1"; }
fresh_evidence() { mkdir -p "$(dirname "$1")"; [[ ! -e "$1" ]] || { printf 'evidence path already exists: %s\n' "$1" >&2; return 2; }; }
chart_sha256() {
  local chart_file="$1"
  [[ -n "$chart_file" && -f "$chart_file" ]] || return 0
  sha256sum -- "$chart_file" | awk '{print $1}'
}

if [[ "$MODE" == cleanup ]]; then
  CLEANUP_STAGE=cleanup-retry-started
  ACTIVE_PHASE=cleanup-retry
  mkdir -p "$RUN_DIR/cleanup"
  # The lifecycle run performs cleanup before reporting success. The workflow's
  # unconditional cleanup step can then verify that exact recorded teardown
  # instead of rerunning API-facing helpers against a deleted Kind cluster.
  if [[ ! -f "$KUBECONFIG" && -s "$RUN_DIR/cleanup/destroy-kind/RESULT.json" ]] && \
     jq -e '.status=="PASS" and .cluster_removed and .registry_removed and .network_removed' \
       "$RUN_DIR/cleanup/destroy-kind/RESULT.json" >/dev/null 2>&1 && \
     ! kind get clusters 2>/dev/null | grep -Fxq "$CLUSTER_NAME" && \
     ! docker container inspect "$REGISTRY_NAME" >/dev/null 2>&1 && \
     ! docker network inspect "$NETWORK_NAME" >/dev/null 2>&1; then
    CLEANUP_STAGE=already-cleaned-confirmed
    jq -n --arg run "$RUN_ID" --arg cluster "$CLUSTER_NAME" \
      '{status:"PASS",runId:$run,cluster:$cluster,naturalCleanup:true,alreadyCleanedByLifecycle:true}' \
      >"$RUN_DIR/cleanup/RESULT.json"
    exit 0
  fi
  if [[ -f "$BOOTSTRAP_EVIDENCE/run-id.txt" && ! -f "$KUBECONFIG" ]] && \
     kind get clusters 2>/dev/null | grep -Fxq "$CLUSTER_NAME"; then
    [[ "$(<"$BOOTSTRAP_EVIDENCE/run-id.txt")" == "$RUN_ID" ]] || {
      printf 'bootstrap run ID mismatch; refusing to recover the private kubeconfig\n' >&2; exit 2;
    }
    CLEANUP_STAGE=private-kubeconfig-recovery
    mkdir -p "$(dirname "$KUBECONFIG")"
    kind export kubeconfig --name "$CLUSTER_NAME" --kubeconfig "$KUBECONFIG" \
      >"$RUN_DIR/logs/kubeconfig-recovery.log" 2>&1
    chmod 0600 "$KUBECONFIG"
  fi
  set +e
  cleanup_rc=0
  if [[ -f "$BOOTSTRAP_EVIDENCE/run-id.txt" && -f "$KUBECONFIG" ]]; then
    CLEANUP_STAGE=exporting-cleanup-environment
    EXPECTED_API_SERVER="$(kubectl --kubeconfig="$KUBECONFIG" --context="$KUBE_CONTEXT" config view --minify -o jsonpath='{.clusters[0].cluster.server}' 2>/dev/null || true)"
    export KUBECONFIG KUBE_CONTEXT EXPECTED_API_SERVER GRID_RUN_LABEL="$RUN_ID" E2E_RUN_ID="$RUN_ID"
    export GRID_LLMD_CLUSTER_PLATFORM=kind CLUSTER_ENV=kind RESOURCE_PROFILE=reduced-dev
    export GRID_OPERATOR_NAMESPACE GRID_RESOURCE_NAMESPACE GRID_NETWORK_NAME GRID_SITE_NAME
    export GRID_GATEWAY_RELEASE_NAME GRID_OPERATOR_RELEASE_NAME KIND_CLUSTER_NAME="$CLUSTER_NAME"
    export KIND_MAAS_CLEANUP_STATE_FILE="$STATE_DIR/maas-cleanup-state.json"
    export KIND_MAAS_CLEANUP_STATE_FILE_FOR_KIND="$STATE_DIR/maas-cleanup-state.json"
    GRID_OPERATOR_IMAGE="$(image_ref grid-operator 2>/dev/null || true)"
    GRID_OPERATOR_SOURCE_REVISION="$(source_value grid-operator 2>/dev/null || true)"
    GRID_GATEWAY_SOURCE_REVISION="$(source_value grid 2>/dev/null || true)"
    GRID_SOURCE_REVISION="$GRID_GATEWAY_SOURCE_REVISION"
    EPP_SOURCE_REVISION="$(source_value epp 2>/dev/null || true)"
    SIMULATOR_SOURCE_REVISION="$(source_value llm-d-sim 2>/dev/null || true)"
    EXTPROC_SOURCE_REVISION="$(source_value extproc 2>/dev/null || true)"
    EPP_IMAGE="$(image_ref epp 2>/dev/null || true)"
    SIMULATOR_IMAGE="$(image_ref llm-d-sim 2>/dev/null || true)"
    EXTPROC_IMAGE="$(image_ref extproc 2>/dev/null || true)"
    GRID_OPERATOR_CHART_FILE="$(find "$STATE_DIR/charts/grid-operator" -maxdepth 1 -type f -name 'grid-operator-*.tgz' -print -quit 2>/dev/null || true)"
    CLEANUP_STAGE=grid-operator-chart-checksum
    GRID_OPERATOR_CHART_SHA256="$(chart_sha256 "$GRID_OPERATOR_CHART_FILE")"
    PRAXIS_GATEWAY_CHART_FILE="$(find "$STATE_DIR/charts/praxis-gateway" -maxdepth 1 -type f -name 'praxis-gateway-*.tgz' -print -quit 2>/dev/null || true)"
    CLEANUP_STAGE=praxis-gateway-chart-checksum
    PRAXIS_GATEWAY_CHART_SHA256="$(chart_sha256 "$PRAXIS_GATEWAY_CHART_FILE")"
    export GRID_OPERATOR_CHART_FILE GRID_OPERATOR_IMAGE GRID_OPERATOR_SOURCE_REVISION GRID_GATEWAY_SOURCE_REVISION GRID_SOURCE_REVISION
    export EPP_SOURCE_REVISION SIMULATOR_SOURCE_REVISION EXTPROC_SOURCE_REVISION
    export EPP_IMAGE SIMULATOR_IMAGE EXTPROC_IMAGE GRID_OPERATOR_CHART_SHA256
    export PRAXIS_GATEWAY_CHART_FILE PRAXIS_GATEWAY_CHART_SHA256
    export GRID_RESOURCE_NAMESPACE GRID_GATEWAY_HOSTNAME="$SITE_HOSTNAME"
    if [[ -f "$RUN_DIR/grid/providers/grid-praxis-cluster-endpoints.json" ]]; then
      CLEANUP_STAGE=provider-cleanup
      GRID_PROVIDERS_MODE=cleanup GRID_PROVIDERS_EVIDENCE_DIR="$RUN_DIR/cleanup/providers-$(date -u +%H%M%S)" \
        bash "$(helper deploy-grid-providers.sh)" || cleanup_rc=$?
    fi
    if [[ -d "$RUN_DIR/serving/pool-a" || -d "$RUN_DIR/serving/pool-b" ]]; then
      CLEANUP_STAGE=serving-pool-cleanup
      KIND_SERVING_CLEANUP_MODE=fresh KIND_SERVING_CLEANUP_EVIDENCE_DIR="$RUN_DIR/cleanup/serving-$(date -u +%H%M%S)" \
        bash "$(helper cleanup-kind-serving.sh)" || cleanup_rc=$?
    fi
    if [[ -f "$RUN_DIR/grid/operator-bootstrap/RESULT.json" ]]; then
      CLEANUP_STAGE=grid-operator-cleanup
      GRID_OPERATOR_CLEANUP_MODE=cleanup GRID_OPERATOR_CLEANUP_EVIDENCE_DIR="$RUN_DIR/cleanup/grid-operator-$(date -u +%H%M%S)" \
        bash "$(helper cleanup-grid-operator.sh)" || cleanup_rc=$?
    fi
    if [[ -f "$RUN_DIR/platform/task-namespace/RESULT.json" ]]; then
      CLEANUP_STAGE=task-namespace-cleanup
      KIND_TASK_CLEANUP_MODE=fresh KIND_TASK_CLEANUP_EVIDENCE_DIR="$RUN_DIR/cleanup/task-namespace-$(date -u +%H%M%S)" \
        bash "$(helper cleanup-kind-task-namespace.sh)" || cleanup_rc=$?
    fi
    # On a failed run, the natural application cleanup attempt is preserved
    # above; the exact run-owned cluster is still removed so no workload leaks.
    CLEANUP_STAGE=kind-registry-network-destroy
    KIND_DESTROY_EVIDENCE_DIR="$RUN_DIR/cleanup/destroy-kind" \
      KIND_ENV_EVIDENCE_DIR="$BOOTSTRAP_EVIDENCE" KIND_STATE_DIR="$KIND_STATE_DIR" \
      E2E_RUN_ID="$RUN_ID" KIND_CLUSTER_NAME="$CLUSTER_NAME" \
      KIND_REGISTRY_CONTAINER="$REGISTRY_NAME" KIND_REGISTRY_NETWORK="$NETWORK_NAME" \
      KUBECONFIG="$KUBECONFIG" bash "$(helper destroy-kind-environment.sh)" || cleanup_rc=$?
    CLEANUP_STAGE=kind-registry-network-destroy-finished
  else
    if [[ -f "$BOOTSTRAP_EVIDENCE/run-id.txt" ]]; then
      # The cluster disappeared before the natural application cleanup could be
      # observed. Remove only its recorded Docker resources, but keep this run
      # failed because finalizer ordering was not proven.
      CLEANUP_STAGE=kind-destroy-without-api
      KIND_DESTROY_EVIDENCE_DIR="$RUN_DIR/cleanup/destroy-kind" \
        KIND_ENV_EVIDENCE_DIR="$BOOTSTRAP_EVIDENCE" KIND_STATE_DIR="$KIND_STATE_DIR" \
        E2E_RUN_ID="$RUN_ID" KIND_CLUSTER_NAME="$CLUSTER_NAME" \
        KIND_REGISTRY_CONTAINER="$REGISTRY_NAME" KIND_REGISTRY_NETWORK="$NETWORK_NAME" \
        KUBECONFIG="$KUBECONFIG" bash "$(helper destroy-kind-environment.sh)" || cleanup_rc=$?
      CLEANUP_STAGE=kind-destroy-without-api-finished
      jq -n --arg status FAIL --arg run "$RUN_ID" --arg cluster "$CLUSTER_NAME" \
        '{status:$status,runId:$run,cluster:$cluster,naturalCleanup:false,reason:"cluster or kubeconfig unavailable before application cleanup"}' \
        >"$RUN_DIR/cleanup/RESULT.json"
      if ((cleanup_rc != 0)); then exit "$cleanup_rc"; fi
      # The primary lifecycle already failed. Report cleanup success when all
      # remaining run-owned infrastructure was removed, while keeping natural
      # application cleanup explicitly unproven in cleanup/RESULT.json.
      exit 0
    fi
    printf '{"status":"NOT_APPLICABLE","reason":"run-owned Kind bootstrap was not created"}\n' >"$RUN_DIR/cleanup/RESULT.json"
  fi
  set -e
  if ((cleanup_rc != 0)); then exit "$cleanup_rc"; fi
  CLEANUP_STAGE=cleanup-result-writing
  jq -n --arg status PASS --arg run "$RUN_ID" --arg cluster "$CLUSTER_NAME" \
    '{status:$status,runId:$run,cluster:$cluster,naturalCleanup:true}' >"$RUN_DIR/cleanup/RESULT.json"
  phase_start natural-cleanup
  phase_end 0
  if [[ -n "${GITHUB_OUTPUT:-}" ]]; then printf 'evidence_dir=%s\n' "$RUN_DIR" >>"$GITHUB_OUTPUT"; fi
  exit 0
fi

