package_chart() {
  local source="$1" name="$2" dest="$3" chart_dir
  chart_dir="$(python3 - "$source" "$name" <<'PY'
import re, sys
from pathlib import Path
root = Path(sys.argv[1])
expected = sys.argv[2]
for candidate in root.rglob("Chart.yaml"):
    text = candidate.read_text(encoding="utf-8")
    if re.search(r"^name:\s*[\"']?" + re.escape(expected) + r"[\"']?\s*$", text, re.MULTILINE):
        print(candidate.parent)
        break
else:
    raise SystemExit(f"chart {expected!r} not found below {root}")
PY
)"
  mkdir -p "$dest"
  chmod 0700 "$dest"
  helm package "$chart_dir" --destination "$dest" >"$RUN_DIR/logs/package-$name.log"
  find "$dest" -maxdepth 1 -type f -name "$name-*.tgz" -print -quit
}

